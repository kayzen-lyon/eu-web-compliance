#!/usr/bin/env python3
"""Check or regenerate the official RGAA text held in the skill.

Adapted from two scripts of the DINUM skill `rgaa`:
  skills/rgaa/scripts/officiel.py and skills/rgaa/scripts/check-classement.py
  https://github.com/etalab-ia/skills (commit 0eae080, 2026-11-09)
  MIT License, Copyright (c) 2026 Benoit Vinceneux.
Changes made here: one generated file per theme instead of blocks inside
hand-written files, English labels around the French official text, glossary
links kept as links, version taken from the ACTIVE file, evaluation modes read
from a JSON file, and the RGAA part of mapping.json generated as well.

The RGAA version comes from `references/accessibility/rgaa/ACTIVE`. For that
version the script reads, never edits:

  <version>/sources/criteres.json     official criteria (DINUM)
  <version>/sources/glossaire.json    official glossary (DINUM)
  <version>/evaluation-modes.json     evaluation mode of each criterion

and generates:

  <version>/criteria-NN-<theme>.md    one file per theme
  <version>/glossary.md
  <version>/index.md
  references/accessibility/mapping.json   only the `rgaa` block and the
                                          `rgaa` list of each WCAG entry

Official text is copied character for character. The only change is the
target of glossary links: `(#anchor)` becomes `(glossary.md#anchor)`.

Usage:
    python scripts/rgaa_official.py           # check: generated files match the source
    python scripts/rgaa_official.py --write   # regenerate

Exit codes: 0 no difference, 1 difference or inconsistency, 2 usage or read
error. Standard library only; Python 3.8 or later.
"""

from __future__ import annotations

import argparse
import html
import json
import re
import sys
import unicodedata
from pathlib import Path
from typing import Dict, List, NamedTuple, Optional, Tuple

ROOT = Path(__file__).resolve().parent.parent
RGAA_REL = "references/accessibility/rgaa"
MAPPING_REL = "references/accessibility/mapping.json"

MODES = ("code", "mixed", "real-conditions", "human-judgement")
VERSION = re.compile(r"^[0-9]+(\.[0-9]+)*$")
CRITERION_ID = re.compile(r"^[0-9]+\.[0-9]+$")
GLOSSARY_LINK = re.compile(r"\]\(#([^)\s]+)\)")
WCAG_LABEL = re.compile(r"^(\d+\.\d+\.\d+) (.+) \((A{1,3})\)$")
GENERATED_NAME = re.compile(r"^(criteria-\d+-[a-z0-9-]+|glossary|index)\.md$")

GENERATED_NOTE = (
    "> Generated by `scripts/rgaa_official.py` from the official files in `sources/`. "
    "Do not edit by hand: run `python scripts/rgaa_official.py --write`."
)
OFFICIAL_NOTE = (
    "> The French text is the official RGAA text (DINUM, Licence Ouverte 2.0), copied without change "
    "and never translated. Headings and labels in English are not part of the RGAA."
)
NO_RGAA_NOTE = "No criterion of RGAA {version} lists this success criterion in the official criteres.json."


class CheckError(Exception):
    """Usage or read error: exit code 2."""


class Criterion(NamedTuple):
    number: str
    title: str
    tests: Tuple[Tuple[str, Tuple[str, ...]], ...]  # (test number, lines of the test)
    special_cases: tuple
    technical_notes: tuple
    wcag_labels: Tuple[str, ...]
    techniques: Tuple[str, ...]


class Theme(NamedTuple):
    number: int
    name: str
    criteria: Tuple[Criterion, ...]


# --- reading ---------------------------------------------------------------

def read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        raise CheckError(f"cannot read {path}: {exc}") from exc


def reject_duplicates(pairs: list) -> dict:
    keys = [key for key, _ in pairs]
    doubles = sorted({key for key in keys if keys.count(key) > 1})
    if doubles:
        raise ValueError("duplicate key(s): " + ", ".join(doubles))
    return dict(pairs)


def read_json(path: Path):
    try:
        return json.loads(read_text(path), object_pairs_hook=reject_duplicates)
    except ValueError as exc:
        raise CheckError(f"invalid JSON in {path}: {exc}") from exc


def active_version(root: Path) -> str:
    version = read_text(root / RGAA_REL / "ACTIVE").strip()
    if not VERSION.match(version):
        raise CheckError(f"ACTIVE holds {version!r}: a version number such as 4.1.2 is expected")
    return version


def as_tuple(value) -> tuple:
    """Nested lists become tuples so that parsed data cannot be mutated."""
    if isinstance(value, list):
        return tuple(as_tuple(item) for item in value)
    if isinstance(value, dict):
        return tuple((key, as_tuple(item)) for key, item in value.items())
    return value


def parse_criteria(data: dict) -> Tuple[Theme, ...]:
    try:
        themes = []
        for topic in data["topics"]:
            criteria = []
            for wrapper in topic["criteria"]:
                raw = wrapper["criterium"]
                references = raw.get("references") or []
                criteria.append(Criterion(
                    number=f"{topic['number']}.{raw['number']}",
                    title=raw["title"],
                    tests=tuple((index, tuple(lines)) for index, lines in raw["tests"].items()),
                    special_cases=as_tuple(raw.get("particularCases") or []),
                    technical_notes=as_tuple(raw.get("technicalNote") or []),
                    wcag_labels=tuple(label for ref in references for label in ref.get("wcag", [])),
                    techniques=tuple(item for ref in references for item in ref.get("techniques", [])),
                ))
            themes.append(Theme(int(topic["number"]), topic["topic"], tuple(criteria)))
        return tuple(themes)
    except (KeyError, TypeError, AttributeError, ValueError) as exc:
        raise CheckError(f"criteres.json does not have the expected structure: {exc!r}") from exc


def slug(text: str) -> str:
    """Anchor of a glossary title, as used by the links of criteres.json."""
    text = unicodedata.normalize("NFD", html.unescape(text).lower().replace("œ", "oe"))
    text = "".join(char for char in text if unicodedata.category(char) != "Mn")
    return re.sub(r"[^a-z0-9]+", "-", text).strip("-")


# --- evaluation modes --------------------------------------------------------

def check_modes(modes: dict, themes: Tuple[Theme, ...]) -> List[str]:
    """Ported from check-classement.py: one known mode per criterion, no unknown criterion."""
    entries = modes.get("criteria")
    if not isinstance(entries, dict):
        return ["evaluation-modes.json: object `criteria` missing"]
    checks = (modes.get("meta") or {}).get("checks") or {}
    known = [criterion.number for theme in themes for criterion in theme.criteria]
    errors = [f"evaluation-modes.json: criterion {number} has no mode" for number in known if number not in entries]
    errors += [f"evaluation-modes.json: criterion {number} is not in criteres.json"
               for number in entries if number not in known]
    for number, entry in entries.items():
        if not isinstance(entry, dict):
            errors.append(f"evaluation-modes.json: criterion {number} is not an object")
            continue
        mode, check = entry.get("mode"), entry.get("check")
        if mode not in MODES:
            errors.append(f"evaluation-modes.json: criterion {number} has unknown mode {mode!r} "
                          f"(expected: {', '.join(MODES)})")
            continue
        if mode == "code" and (check or entry.get("code_proves") or entry.get("remains")):
            errors.append(f"evaluation-modes.json: criterion {number} is `code` and carries nothing else")
        if mode != "code" and not entry.get("remains"):
            errors.append(f"evaluation-modes.json: criterion {number} needs `remains`")
        if mode == "mixed" and not entry.get("code_proves"):
            errors.append(f"evaluation-modes.json: criterion {number} is `mixed` and needs `code_proves`")
        if mode in ("real-conditions", "human-judgement") and entry.get("code_proves"):
            errors.append(f"evaluation-modes.json: criterion {number} is `{mode}`: `code_proves` must be null")
        if mode == "real-conditions" and not check:
            errors.append(f"evaluation-modes.json: criterion {number} is `real-conditions` and names its `check`")
        if check and check not in checks:
            errors.append(f"evaluation-modes.json: criterion {number} names unknown check {check!r}")
    return errors


# --- rendering -----------------------------------------------------------------

def official(text: str, anchors: frozenset) -> str:
    """Official text unchanged, except the target of links to a glossary entry."""
    return GLOSSARY_LINK.sub(
        lambda match: f"](glossary.md#{match.group(1)})" if match.group(1) in anchors else match.group(0), text)


def unresolved_anchors(themes: Tuple[Theme, ...], anchors: frozenset) -> List[str]:
    found = set()

    def visit(value) -> None:
        if isinstance(value, str):
            found.update(anchor for anchor in GLOSSARY_LINK.findall(value) if anchor not in anchors)
        elif isinstance(value, tuple):
            for item in value:
                visit(item)

    for theme in themes:
        for criterion in theme.criteria:
            visit((criterion.title, criterion.tests, criterion.special_cases, criterion.technical_notes))
    return sorted(found)


def render_notes(entries: tuple, anchors: frozenset) -> List[str]:
    """Paragraphs and lists of `particularCases` and `technicalNote`.

    Items of a `ul` list already start with "- " in the source: they are copied as they are.
    """
    lines: List[str] = []
    for entry in entries:
        if isinstance(entry, str):
            lines += [official(entry, anchors), ""]
        elif len(entry) == 1 and entry[0][0] == "ul" and all(isinstance(item, str) for item in entry[0][1]):
            lines += [official(item, anchors) for item in entry[0][1]] + [""]
        else:
            raise CheckError(f"unexpected structure in criteres.json: {entry!r}")
    return lines


def render_mode(entry: dict) -> List[str]:
    lines = ["### Evaluation mode (provisional, not part of the RGAA)", "", f"- **Mode:** `{entry['mode']}`"]
    if entry.get("check"):
        lines.append(f"- **Real-conditions check:** `{entry['check']}`")
    if entry.get("code_proves"):
        lines.append(f"- **Code proves:** {entry['code_proves']}")
    if entry.get("remains"):
        lines.append(f"- **Remains for a person:** {entry['remains']}")
    return lines + [""]


def render_criterion(criterion: Criterion, mode: dict, anchors: frozenset) -> List[str]:
    lines = [f"## Criterion {criterion.number}", "", f"**Official title:** {official(criterion.title, anchors)}", ""]
    lines += ["### Tests", ""]
    for index, test in criterion.tests:
        lines.append(f"- **{criterion.number}.{index}** {official(test[0], anchors)}")
        lines += [f"  - {official(condition, anchors)}" for condition in test[1:]]
    lines.append("")
    if criterion.special_cases:
        lines += ["### Special cases (cas particuliers)", ""] + render_notes(criterion.special_cases, anchors)
    if criterion.technical_notes:
        lines += ["### Technical notes (notes techniques)", ""] + render_notes(criterion.technical_notes, anchors)
    lines += ["### WCAG references listed by the official file", ""]
    lines.append("- **Success criteria:** " + ("; ".join(criterion.wcag_labels) or "none listed"))
    lines.append("- **Techniques:** " + (", ".join(criterion.techniques) or "none listed"))
    lines.append("")
    return lines + render_mode(mode)


def theme_file(theme: Theme) -> str:
    return f"criteria-{theme.number:02d}-{slug(theme.name)}.md"


def render_theme(theme: Theme, version: str, wcag_version: str, modes: dict, anchors: frozenset) -> str:
    lines = [
        f"# RGAA {version} — Theme {theme.number}: {theme.name}",
        "",
        GENERATED_NOTE,
        ">",
        OFFICIAL_NOTE,
        ">",
        f"> WCAG references are those listed by the official file, which targets WCAG {wcag_version}. "
        "Evaluation modes come from `evaluation-modes.json`: they are provisional and not official.",
        "",
        f"{len(theme.criteria)} criteria. Glossary: [glossary.md](glossary.md). All themes: [index.md](index.md).",
        "",
    ]
    note = (modes.get("theme_notes") or {}).get(str(theme.number))
    if note:
        lines += [f"Evaluation note (provisional, not official): {note}", ""]
    for criterion in theme.criteria:
        lines += render_criterion(criterion, modes["criteria"][criterion.number], anchors)
    return "\n".join(lines).rstrip("\n") + "\n"


def render_glossary(glossary: dict, version: str) -> str:
    try:
        entries = [(entry["title"], entry["body"]) for entry in glossary["glossary"]]
    except (KeyError, TypeError) as exc:
        raise CheckError(f"glossaire.json does not have the expected structure: {exc!r}") from exc
    lines = [
        f"# RGAA {version} — Official glossary",
        "",
        GENERATED_NOTE,
        ">",
        OFFICIAL_NOTE,
        ">",
        "> Each definition is the HTML of the official file, unchanged. The anchor before each title is the one "
        "used by the links of the criteria files.",
        "",
        f"{len(entries)} entries.",
        "",
    ]
    for title, body in entries:
        lines += [f'<a id="{slug(title)}"></a>', "", f"## {title}", "", body.strip("\n"), ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def render_index(themes: Tuple[Theme, ...], version: str, modes: dict, dangling: List[str]) -> str:
    entries = modes["criteria"]
    total = sum(len(theme.criteria) for theme in themes)
    lines = [
        f"# RGAA {version} — Index of generated files",
        "",
        GENERATED_NOTE,
        "",
        f"{total} criteria in {len(themes)} themes. Official files: [sources/README.md](sources/README.md). "
        "Glossary: [glossary.md](glossary.md). Evaluation modes (provisional, not official): "
        "`evaluation-modes.json`.",
        "",
        "| Theme | Official name | File | Criteria | " + " | ".join(f"`{mode}`" for mode in MODES) + " |",
        "|---|---|---|---|" + "---|" * len(MODES),
    ]
    for theme in themes:
        counts = [sum(1 for c in theme.criteria if entries[c.number]["mode"] == mode) for mode in MODES]
        lines.append(f"| {theme.number} | {theme.name} | [{theme_file(theme)}]({theme_file(theme)}) | "
                     f"{len(theme.criteria)} | " + " | ".join(str(count) for count in counts) + " |")
    totals = [sum(1 for entry in entries.values() if entry["mode"] == mode) for mode in MODES]
    lines.append(f"| | Total | | {total} | " + " | ".join(str(count) for count in totals) + " |")
    lines.append("")
    if dangling:
        lines += ["Links of the official criteria whose anchor has no entry in the official glossary (left as "
                  "they are in the source): " + ", ".join(f"`#{anchor}`" for anchor in dangling) + ".", ""]
    return "\n".join(lines)


# --- mapping.json ------------------------------------------------------------

def sc_key(number: str) -> Tuple[int, ...]:
    return tuple(int(part) for part in number.split("."))


def build_mapping(mapping: dict, themes: Tuple[Theme, ...], version: str, wcag_version: str) -> Tuple[dict, List[str]]:
    """New mapping whose RGAA parts are rebuilt from the official file; the rest is kept as it is."""
    table = mapping.get("wcag")
    if not isinstance(table, dict):
        return mapping, ["mapping.json: object `wcag` missing"]
    errors: List[str] = []
    criteria: Dict[str, dict] = {}
    reverse: Dict[str, List[str]] = {}
    for theme in themes:
        for criterion in theme.criteria:
            numbers = []
            for label in criterion.wcag_labels:
                match = WCAG_LABEL.match(label)
                if not match:
                    errors.append(f"criteres.json: criterion {criterion.number}: unreadable WCAG reference {label!r}")
                    continue
                number = match.group(1)
                if number not in table:
                    errors.append(f"mapping.json: WCAG {number}, listed by criterion {criterion.number}, has no "
                                  "entry in `wcag` (add it by hand from the official sources, never by guessing)")
                    continue
                if number not in numbers:
                    numbers.append(number)
                    reverse.setdefault(number, []).append(criterion.number)
            criteria[criterion.number] = {"wcag": sorted(numbers, key=sc_key),
                                          "source_labels": list(criterion.wcag_labels)}
    wcag = {}
    for number, entry in table.items():
        listed = reverse.get(number)
        wcag[number] = {**entry, "rgaa": listed or None,
                        "rgaa_note": None if listed else NO_RGAA_NOTE.format(version=version)}
    rgaa = {"version": version, "wcag_version_of_source": wcag_version, "criteria": criteria}
    return {**mapping, "rgaa": rgaa, "wcag": wcag}, errors


def dump_json(data: dict) -> str:
    return json.dumps(data, ensure_ascii=False, indent=2) + "\n"


# --- check or write --------------------------------------------------------------

def expected_files(root: Path, version: str) -> Tuple[Dict[Path, str], List[str]]:
    base = root / RGAA_REL / version
    data = read_json(base / "sources" / "criteres.json")
    themes = parse_criteria(data)
    glossary = read_json(base / "sources" / "glossaire.json")
    modes = read_json(base / "evaluation-modes.json")
    errors = check_modes(modes, themes)
    if errors:
        return {}, errors
    wcag_version = str((data.get("wcag") or {}).get("version", "unknown"))
    anchors = frozenset(slug(entry["title"]) for entry in glossary.get("glossary", []) if "title" in entry)
    files = {base / theme_file(theme): render_theme(theme, version, wcag_version, modes, anchors) for theme in themes}
    if len(files) != len(themes):
        raise CheckError("two themes produce the same file name")
    files[base / "glossary.md"] = render_glossary(glossary, version)
    files[base / "index.md"] = render_index(themes, version, modes, unresolved_anchors(themes, anchors))
    mapping_path = root / MAPPING_REL
    mapping, mapping_errors = build_mapping(read_json(mapping_path), themes, version, wcag_version)
    files[mapping_path] = dump_json(mapping)
    total = sum(len(theme.criteria) for theme in themes)
    print(f"RGAA {version}: {total} criteria in {len(themes)} themes read from the official file.")
    return files, mapping_errors


def run(root: Path, write: bool) -> int:
    version = active_version(root)
    base = root / RGAA_REL / version
    files, errors = expected_files(root, version)
    written = 0
    if not errors:
        for path, content in files.items():
            current = path.read_bytes().decode("utf-8", errors="replace") if path.is_file() else None
            if current == content:
                continue
            if write:
                path.write_bytes(content.encode("utf-8"))  # bytes: LF line endings on every platform
                written += 1
                print(f"written: {path.relative_to(root).as_posix()}")
            else:
                state = "missing" if current is None else "differs from the source"
                errors.append(f"{path.relative_to(root).as_posix()}: {state} (run with --write)")
        errors += [f"{path.relative_to(root).as_posix()}: generated file with no counterpart in the source "
                   "(delete it)" for path in sorted(base.glob("*.md"))
                   if GENERATED_NAME.match(path.name) and path not in files]
    for message in errors:
        print(message)
    action = f"{written} written" if write else "checked"
    print(f"{len(files)} generated file(s) {action}; {len(errors)} error(s).")
    return 1 if errors else 0


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Check or regenerate the official RGAA text held in the skill.")
    parser.add_argument("--write", action="store_true", help="regenerate the files instead of checking them")
    parser.add_argument("--root", default=str(ROOT), help="repository root (default: parent of scripts/)")
    args = parser.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):  # readable accents in a Windows console
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    try:
        return run(Path(args.root).resolve(), args.write)
    except CheckError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
