"""Rebuilds examples/ai-news/faulty from fixed and plants the AI and consumer-law defects.
Usage: python scripts/examples/plant_ai_news.py examples
Run it after any change to fixed/: faulty/ is generated, never edited by hand.
The defects are listed in examples/ai-news/expected-content.json; each comment below gives
the id of the entry it plants."""
import shutil
import sys
from pathlib import Path

site = Path(sys.argv[1]) / "ai-news"
fixed, faulty = site / "fixed", site / "faulty"
if faulty.exists():
    shutil.rmtree(faulty)
shutil.copytree(fixed, faulty)


def edit(name, pairs):
    path = faulty / name
    text = path.read_text(encoding="utf-8")
    for old, new in pairs:
        if text.count(old) != 1:
            raise SystemExit(f"{name}: expected exactly one occurrence of {old[:70]!r}, found {text.count(old)}")
        text = text.replace(old, new)
    path.write_bytes(text.encode("utf-8"))


def badge(word):
    return f'          <span class="ai-badge"><span class="ai-badge__mark" aria-hidden="true">AI</span> {word}<span class="visually-hidden"> image</span></span>\n'


